import { useLayoutEffect, useRef, type MouseEvent } from 'react'
import { suggestions, type ProjectKey } from '../content'
import type { Composer } from '../useChat'
import { Thumb } from './Thumb'

type Props = {
  composer: Composer
  /** The chips hide once the conversation has started. */
  started: boolean
  onProject: (e: MouseEvent, key: ProjectKey) => void
  /** What the visitor has typed. Empty means send runs the queued scripted question. */
  draft: string
  onDraft: (text: string) => void
  onSubmit: () => void
}

export function Dock({ composer, started, onProject, draft, onDraft, onSubmit }: Props) {
  const box = useRef<HTMLTextAreaElement | null>(null)
  // Grow with the text, up to a few lines.
  useLayoutEffect(() => {
    const el = box.current
    if (!el) return
    el.style.height = 'auto'
    el.style.height = `${Math.min(el.scrollHeight, 120)}px`
  }, [draft])
  const canSend = !composer.disabled && (draft.trim() !== '' || !composer.empty)

  return (
    <div className="dock">
      <div className={'suggestions' + (started ? ' is-hidden' : '')} id="suggestions">
        {suggestions.map((s) => (
          <button key={s.title} className="sugg" onClick={(e) => onProject(e, s.project)}>
            <Thumb src={s.img} />
            <span className="sugg__body">
              <span className="sugg__tag">{s.tag}</span>
              <span className="sugg__title">{s.title}</span>
              <span className="sugg__sub">{s.sub}</span>
              <span className="sugg__tags">{s.tags.map((t) => <span key={t}>{t}</span>)}</span>
            </span>
          </button>
        ))}
      </div>

      <form className="composer" id="composer" onSubmit={(e) => { e.preventDefault(); onSubmit() }}>
        <div className="composer__row">
          <textarea
            ref={box}
            className="composer__text composer__input"
            id="composer-text"
            rows={1}
            maxLength={600}
            value={draft}
            placeholder={composer.empty ? 'Ask me anything about my work' : composer.text}
            aria-label="Ask a question"
            disabled={composer.disabled}
            onChange={(e) => onDraft(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter' && !e.shiftKey && !e.nativeEvent.isComposing) {
                e.preventDefault()
                if (canSend) onSubmit()
              }
            }}
          />
          <button className="send" type="submit" aria-label="Send" disabled={!canSend}>
            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round"><path d="M12 19V5M5 12l7-7 7 7" /></svg>
          </button>
        </div>
      </form>
      <p className="dock__meta">Replies run on natural intelligence, generated by Akanksha herself. She drinks less water than ChatGPT.</p>
    </div>
  )
}
